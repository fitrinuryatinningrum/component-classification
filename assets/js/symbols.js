/* ---------- Helper ---------- */
function _arrow(x1, y1, x2, y2, head) {
  head = head || 6;
  const a = Math.atan2(y2 - y1, x2 - x1);
  const p1x = (x2 - head * Math.cos(a - 0.42)).toFixed(1);
  const p1y = (y2 - head * Math.sin(a - 0.42)).toFixed(1);
  const p2x = (x2 - head * Math.cos(a + 0.42)).toFixed(1);
  const p2y = (y2 - head * Math.sin(a + 0.42)).toFixed(1);
  return `M${x1} ${y1} L${x2} ${y2} M${p1x} ${p1y} L${x2} ${y2} L${p2x} ${p2y}`;
}

/**
 * Render simbol sebagai string SVG.
 * @param {string} key - kunci simbol pada SYMBOLS
 * @param {string} cls - class CSS tambahan
 * @param {string} title - label aksesibilitas
 */
function symbolSVG(key, cls, title) {
  const s = SYMBOLS[key] || SYMBOLS.resistor;
  cls = cls || "";
  let inner = "";
  (s.c || []).forEach(function (c) {
    inner += `<circle cx="${c[0]}" cy="${c[1]}" r="${c[2]}"/>`;
  });
  (s.p || []).forEach(function (d) { inner += `<path d="${d}"/>`; });
  (s.t || []).forEach(function (t) { inner += `<text x="${t[0]}" y="${t[1]}" class="sym-t">${t[2]}</text>`; });
  if (s.h) inner += Array.isArray(s.h) ? s.h.join("") : s.h;
  const vw = s.vw || "0 0 80 40";
  const lbl = title ? `role="img" aria-label="${title}"` : `aria-hidden="true"`;
  return `<svg class="sym ${cls}" viewBox="${vw}" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round" ${lbl}>${inner}</svg>`;
}

